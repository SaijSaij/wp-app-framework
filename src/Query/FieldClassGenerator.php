<?php

declare(strict_types=1);

namespace Saij\WpAppFramework\Query;

use Saij\WpAppFramework\DependencyInjection\NoService;
use Saij\WpAppFramework\Query\Field\Field;

/**
 * Writes the source of a field class: one static method per field, next to the class the fields belong to
 * (`wp-app-framework meta-fields <meta class>`, `wp-app-framework table-fields <row class>`). The result is ordinary
 * source code of the theme or plugin.
 *
 * @internal
 */
#[NoService]
final class FieldClassGenerator
{
    /** The suffix of the generated class name. */
    public const string SUFFIX = 'Fields';

    /**
     * @param class-string                                                $owner     The class the fields belong to.
     * @param class-string                                                $attribute The attribute of the field class (MetaFields, TableFields).
     * @param non-empty-string                                            $command   The command that generates the class, e.g. `meta-fields`.
     * @param array<string, array{class-string<Field>, class-string|null}> $fields    Field class and class of the type (enum, post) by field.
     */
    public static function generate(string $owner, string $attribute, string $command, array $fields): string
    {
        $position = strrpos($owner, '\\');
        $namespace = $position === false ? '' : substr($owner, 0, $position);
        $short = $position === false ? $owner : substr($owner, $position + 1);
        $imports = [];
        $name = static function (string $class) use (&$imports, $namespace): string {
            $position = strrpos($class, '\\');
            $classNamespace = $position === false ? '' : substr($class, 0, $position);
            $alias = $position === false ? $class : substr($class, $position + 1);
            if ($classNamespace === $namespace) {
                return $alias;
            }
            if (($imports[$class] ?? null) === $alias) {
                return $alias;
            }
            if (in_array($alias, $imports, true)) {
                return '\\' . $class;
            }
            $imports[$class] = $alias;

            return $alias;
        };
        $attributeName = $name($attribute);

        $methods = [];
        foreach ($fields as $field => [$fieldClass, $typeClass]) {
            $type = $name($fieldClass);
            $arguments = sprintf('%s::class, \'%s\'', $short, $field);
            $doc = '';
            if ($typeClass !== null) {
                $generic = $name($typeClass);
                $arguments .= sprintf(', %s::class', $generic);
                $doc = sprintf("    /**\n     * @return %s<%s>\n     */\n", $type, $generic);
            }
            $methods[] = sprintf("%s    public static function %s(): %s\n    {\n        return new %s(%s);\n    }\n", $doc, $field, $type, $type, $arguments);
        }

        ksort($imports);
        $uses = implode('', array_map(static fn(string $class): string => sprintf("use %s;\n", $class), array_keys($imports)));

        return sprintf(
            "<?php\n\ndeclare(strict_types=1);\n\n%s%s\n/**\n * The fields of %s for queries; generated by `wp-app-framework %s`, change it as you like.\n */\n#[%s(%s::class)]\nfinal class %s%s\n{\n%s}\n",
            $namespace === '' ? '' : sprintf("namespace %s;\n\n", $namespace),
            $uses,
            $short,
            $command,
            $attributeName,
            $short,
            $short,
            self::SUFFIX,
            implode("\n", $methods),
        );
    }

    /**
     * The file of the field class: `{Owner}Fields.php` in the directory of the class the fields belong to.
     */
    public static function file(string $ownerFile, string $owner): string
    {
        return dirname($ownerFile) . '/' . substr($owner, (int) strrpos('\\' . $owner, '\\')) . self::SUFFIX . '.php';
    }
}
