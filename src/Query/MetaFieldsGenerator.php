<?php

declare(strict_types=1);

namespace Saij\WpAppFramework\Query;

use Saij\WpAppFramework\DependencyInjection\NoService;
use Saij\WpAppFramework\Query\Field\FieldTypes;
use Saij\WpAppFramework\Value\ValueFactory;

/**
 * Writes the source of a class with #[MetaFields] for a meta class: one method per field that can be queried
 * (`wp-app-framework meta-fields <meta class>`). The result is ordinary source code of the theme or plugin.
 *
 * @internal
 *
 * @phpstan-import-type Value from ValueFactory
 */
#[NoService]
final class MetaFieldsGenerator
{
    /** The suffix of the generated class name. */
    public const string SUFFIX = 'Fields';

    /**
     * @param class-string         $metaClass
     * @param array<string, Value> $values    Values of the meta class by field.
     */
    public static function generate(string $metaClass, array $values): string
    {
        $position = strrpos($metaClass, '\\');
        $namespace = $position === false ? '' : substr($metaClass, 0, $position);
        $short = $position === false ? $metaClass : substr($metaClass, $position + 1);
        $imports = [MetaFields::class => 'MetaFields'];
        $name = static function (string $class) use (&$imports, $namespace): string {
            $position = strrpos($class, '\\');
            $classNamespace = $position === false ? '' : substr($class, 0, $position);
            $alias = $position === false ? $class : substr($class, $position + 1);
            if ($classNamespace === $namespace) {
                return $alias;
            }
            if (($imports[$class] ?? null) === $alias) {
                return $alias;
            }
            if (in_array($alias, $imports, true)) {
                return '\\' . $class;
            }
            $imports[$class] = $alias;

            return $alias;
        };

        $methods = [];
        foreach ($values as $field => $value) {
            $expected = FieldTypes::expected($value);
            if ($expected === null) {
                continue;
            }
            [$fieldClass, $typeClass] = $expected;
            $type = $name($fieldClass);
            $arguments = sprintf('%s::class, \'%s\'', $short, $field);
            $doc = '';
            if ($typeClass !== null) {
                $generic = $name($typeClass);
                $arguments .= sprintf(', %s::class', $generic);
                $doc = sprintf("    /**\n     * @return %s<%s>\n     */\n", $type, $generic);
            }
            $methods[] = sprintf("%s    public static function %s(): %s\n    {\n        return new %s(%s);\n    }\n", $doc, $field, $type, $type, $arguments);
        }

        ksort($imports);
        $uses = implode('', array_map(static fn(string $class): string => sprintf("use %s;\n", $class), array_keys($imports)));

        return sprintf(
            "<?php\n\ndeclare(strict_types=1);\n\n%s%s\n/**\n * The fields of %s for queries; generated by `wp-app-framework meta-fields`, change it as you like.\n */\n#[MetaFields(%s::class)]\nfinal class %s%s\n{\n%s}\n",
            $namespace === '' ? '' : sprintf("namespace %s;\n\n", $namespace),
            $uses,
            $short,
            $short,
            $short,
            self::SUFFIX,
            implode("\n", $methods),
        );
    }
}
