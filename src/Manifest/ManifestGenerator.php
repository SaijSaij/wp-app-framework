<?php

declare(strict_types=1);

namespace Saij\WpAppFramework\Manifest;

use Saij\WpAppFramework\DependencyInjection\NoService;

/**
 * Generates the manifest file: a plain data array exported with var_export().
 * The runtime (container, registrars, value factory) interprets it without
 * reflection; no code is generated.
 *
 * @phpstan-import-type ManifestData from Manifest
 */
#[NoService]
final class ManifestGenerator
{
    /**
     * @param non-empty-string|null $templateVersion Version of the shipped templates (TemplateVersion); required for a
     *                                               release manifest, null for the development cache, which is not
     *                                               rebuilt when only a template changes.
     * @param non-empty-string|null $codeVersion     Version of the shipped PHP code (CodeGeneration::codeVersion());
     *                                               required for a release manifest, null for the development cache.
     */
    public function generate(BuildResult $result, ?string $templateVersion = null, ?string $codeVersion = null): string
    {
        return "<?php\n\n// Generated by saij/wp-app-framework. Do not edit.\n\ndeclare(strict_types=1);\n\nreturn "
            . var_export($this->data($result, $templateVersion, $codeVersion), true)
            . ";\n";
    }

    /**
     * @param non-empty-string|null $templateVersion
     * @param non-empty-string|null $codeVersion
     * @return ManifestData
     */
    private function data(BuildResult $result, ?string $templateVersion, ?string $codeVersion): array
    {
        $hooks = [];
        foreach ($result->getHooks() as $hook) {
            $hooks[] = [
                'name' => $hook->getName(),
                'priority' => $hook->getPriority(),
                'acceptedArgs' => $hook->getAcceptedArgs(),
                'filter' => $hook->isFilter(),
                'class' => $hook->getClass(),
                'method' => $hook->getMethod(),
                'arguments' => $hook->getArguments(),
            ];
        }

        $routes = [];
        foreach ($result->getRoutes() as $route) {
            $routes[] = [
                'namespace' => $route->getNamespace(),
                'route' => $route->getRoute(),
                'methods' => $route->getMethods(),
                'args' => $route->getArgs(),
                'permission' => $route->getPermission(),
                'class' => $route->getClass(),
                'method' => $route->getMethod(),
                'arguments' => $route->getArguments(),
                'void' => $route->isVoid(),
                'cache' => $route->getCache(),
            ];
        }

        $templateCallables = [];
        foreach ($result->getTemplateCallables() as $callable) {
            $templateCallables[] = [
                'kind' => $callable->getKind()->value,
                'name' => $callable->getName(),
                'class' => $callable->getClass(),
                'method' => $callable->getMethod(),
                'html' => $callable->isHtml(),
                'public' => $callable->isPublic(),
            ];
        }

        $blocks = [];
        foreach ($result->getBlocks() as $block) {
            $blocks[] = [
                'name' => $block->getName(),
                'args' => $block->getArgs(),
                'class' => $block->getClass(),
                'arguments' => $block->getArguments(),
                'editor' => $block->getEditor(),
                'excerpt' => $block->getExcerpt(),
                'supports' => $block->getSupports(),
                'viewScript' => $block->getViewScript(),
                'cache' => $block->getCache(),
            ];
        }

        return [
            'format' => Manifest::FORMAT,
            'kind' => $result->getKind()->value,
            'slug' => $result->getSlug(),
            'namespace' => $result->getNamespace(),
            'candidates' => $result->getCandidates(),
            'services' => $result->getServices(),
            'hooks' => $hooks,
            'routes' => $routes,
            'templateCallables' => $templateCallables,
            'blocks' => $blocks,
            'blockCategories' => $result->getBlockCategories(),
            'values' => $result->getValues(),
            'parent' => $result->getParent(),
            'publicApis' => $result->getPublicApis(),
            'templateProviders' => $result->getTemplateProviders(),
            'templateVersion' => $templateVersion,
            'codeVersion' => $codeVersion,
            'styles' => $result->hasStyles(),
            'settings' => ['title' => $result->getSettingsTitle(), 'groups' => $result->getSettings()],
            ...$result->getPosts(),
        ];
    }
}
