<?php

declare(strict_types=1);

namespace Saij\WpAppFramework\Manifest;

use LogicException;
use Saij\WpAppFramework\DependencyInjection\Container;
use Saij\WpAppFramework\DependencyInjection\NoService;

/**
 * Generates the PHP code of the manifest. Only fully qualified class names are
 * written; strings are exported with var_export().
 */
#[NoService]
final class ManifestGenerator
{
    public function generate(BuildResult $result): string
    {
        $container = self::name(Container::class);

        $code = "<?php\n\n// Generated by saij/wp-app-framework. Do not edit.\n\ndeclare(strict_types=1);\n\nreturn [\n";
        $code .= sprintf("    'format' => %d,\n", Manifest::FORMAT);

        $code .= "    'candidates' => [\n";
        foreach ($result->getCandidates() as $class) {
            $code .= sprintf("        %s,\n", self::export($class));
        }
        $code .= "    ],\n";

        $code .= "    'services' => [\n";
        foreach ($result->getServices() as $class => $arguments) {
            $parameters = [];
            foreach ($arguments as $parameter => $service) {
                $parameters[] = sprintf('%s: $c->get(%s::class)', $parameter, self::name($service));
            }
            $code .= sprintf(
                "        %s => static fn (%s \$c): %s => new %s(%s),\n",
                self::export($class),
                $container,
                self::name($class),
                self::name($class),
                implode(', ', $parameters),
            );
        }
        $code .= "    ],\n";

        $code .= "    'hooks' => [\n";
        foreach ($result->getHooks() as $hook) {
            $wordPressParameters = [];
            $parameters = [];
            foreach ($hook->getArguments() as $argument) {
                if (isset($argument['service'])) {
                    $parameters[] = sprintf('%s: $c->get(%s::class)', $argument['param'], self::name($argument['service']));
                } else {
                    $wordPressParameters[] = sprintf('%d => %s', $argument['index'], self::export($argument['param']));
                }
            }

            $code .= "        [\n";
            $code .= sprintf("            'name' => %s,\n", self::export($hook->getName()));
            $code .= sprintf("            'priority' => %d,\n", $hook->getPriority());
            $code .= sprintf("            'acceptedArgs' => %d,\n", $hook->getAcceptedArgs());
            $code .= sprintf("            'filter' => %s,\n", $hook->isFilter() ? 'true' : 'false');
            $code .= sprintf("            'source' => %s,\n", self::export($hook->getClass() . '::' . $hook->getMethod() . '()'));
            $code .= sprintf("            'callback' => static function (%s \$c, array \$args): mixed {\n", $container);

            if ($wordPressParameters !== []) {
                // WordPress arguments are passed only if present, so parameter defaults apply when a hook is
                // fired with fewer arguments, and missing required ones fail like with a plain callback.
                array_unshift($parameters, '...$named');
                $code .= "                \$named = [];\n";
                $code .= sprintf("                foreach ([%s] as \$index => \$name) {\n", implode(', ', $wordPressParameters));
                $code .= "                    if (array_key_exists(\$index, \$args)) {\n";
                $code .= "                        \$named[\$name] = \$args[\$index];\n";
                $code .= "                    }\n";
                $code .= "                }\n\n";
            }

            $code .= sprintf(
                "                return \$c->get(%s::class)->%s(%s);\n",
                self::name($hook->getClass()),
                $hook->getMethod(),
                implode(', ', $parameters),
            );
            $code .= "            },\n";
            $code .= "        ],\n";
        }
        $code .= "    ],\n";

        return $code . "];\n";
    }

    private static function name(string $class): string
    {
        if (preg_match('/^[A-Za-z_\x80-\xff][A-Za-z0-9_\x80-\xff]*(\\\\[A-Za-z_\x80-\xff][A-Za-z0-9_\x80-\xff]*)*$/', $class) !== 1) {
            throw new LogicException(sprintf('"%s" is not a valid class name.', $class));
        }

        return '\\' . $class;
    }

    private static function export(string $value): string
    {
        return var_export($value, true);
    }
}
