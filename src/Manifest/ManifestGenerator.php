<?php

declare(strict_types=1);

namespace Saij\WpAppFramework\Manifest;

use Saij\WpAppFramework\DependencyInjection\NoService;

/**
 * Generates the manifest file: a plain data array exported with var_export().
 * The runtime (container, registrars, value factory) interprets it without
 * reflection; no code is generated.
 *
 * @phpstan-import-type ManifestData from Manifest
 */
#[NoService]
final class ManifestGenerator
{
    public function generate(BuildResult $result): string
    {
        return "<?php\n\n// Generated by saij/wp-app-framework. Do not edit.\n\ndeclare(strict_types=1);\n\nreturn "
            . var_export($this->data($result), true)
            . ";\n";
    }

    /**
     * @return ManifestData
     */
    private function data(BuildResult $result): array
    {
        $hooks = [];
        foreach ($result->getHooks() as $hook) {
            $hooks[] = [
                'name' => $hook->getName(),
                'priority' => $hook->getPriority(),
                'acceptedArgs' => $hook->getAcceptedArgs(),
                'filter' => $hook->isFilter(),
                'class' => $hook->getClass(),
                'method' => $hook->getMethod(),
                'arguments' => $hook->getArguments(),
            ];
        }

        $routes = [];
        foreach ($result->getRoutes() as $route) {
            $routes[] = [
                'namespace' => $route->getNamespace(),
                'route' => $route->getRoute(),
                'methods' => $route->getMethods(),
                'args' => $route->getArgs(),
                'permission' => $route->getPermission(),
                'class' => $route->getClass(),
                'method' => $route->getMethod(),
                'arguments' => $route->getArguments(),
                'void' => $route->isVoid(),
            ];
        }

        $templateCallables = [];
        foreach ($result->getTemplateCallables() as $callable) {
            $templateCallables[] = [
                'kind' => $callable->getKind()->value,
                'name' => $callable->getName(),
                'class' => $callable->getClass(),
                'method' => $callable->getMethod(),
                'html' => $callable->isHtml(),
            ];
        }

        $blocks = [];
        foreach ($result->getBlocks() as $block) {
            $blocks[] = [
                'name' => $block->getName(),
                'args' => $block->getArgs(),
                'class' => $block->getClass(),
                'arguments' => $block->getArguments(),
                'editor' => $block->getEditor(),
            ];
        }

        return [
            'format' => Manifest::FORMAT,
            'candidates' => $result->getCandidates(),
            'services' => $result->getServices(),
            'hooks' => $hooks,
            'routes' => $routes,
            'templateCallables' => $templateCallables,
            'blocks' => $blocks,
            'values' => $result->getValues(),
        ];
    }
}
